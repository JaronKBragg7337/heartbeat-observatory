create or replace function public.habitat_public_snapshot(p_world_key text default 'habitat-v0')
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_world public.habitat_worlds%rowtype;
begin
  select * into v_world from public.habitat_worlds where world_key=p_world_key limit 1;
  if not found then return jsonb_build_object('ok',false,'note','world_not_found'); end if;
  return jsonb_build_object(
    'ok',true,'server_time',now(),
    'world',jsonb_build_object('id',v_world.id,'key',v_world.world_key,'name',v_world.name,'status',v_world.status,'tick',v_world.tick,'bounds',v_world.bounds_json,'metadata',v_world.metadata_json,'updated_at',v_world.updated_at),
    'actors',coalesce((select jsonb_agg(jsonb_build_object('id',a.id,'key',a.actor_key,'name',a.display_name,'kind',a.actor_kind,'status',a.status,'generation',a.current_generation_key,'identity',a.identity_json,'last_seen_at',a.last_seen_at) order by a.created_at) from public.habitat_actors a where exists(select 1 from public.habitat_bodies b where b.world_id=v_world.id and b.actor_id=a.id)),'[]'::jsonb),
    'bodies',coalesce((select jsonb_agg(jsonb_build_object('id',b.id,'key',b.body_key,'actor_id',b.actor_id,'kind',b.body_kind,'position',jsonb_build_object('x',b.pos_x,'y',b.pos_y,'z',b.pos_z),'yaw',b.yaw,'state',b.state_json,'last_action_at',b.last_action_at,'updated_at',b.updated_at) order by b.created_at) from public.habitat_bodies b where b.world_id=v_world.id),'[]'::jsonb),
    'objects',coalesce((select jsonb_agg(jsonb_build_object('id',o.id,'key',o.object_key,'kind',o.object_kind,'position',jsonb_build_object('x',o.pos_x,'y',o.pos_y,'z',o.pos_z),'yaw',o.yaw,'scale',jsonb_build_object('x',o.scale_x,'y',o.scale_y,'z',o.scale_z),'state',o.state_json) order by o.object_key) from public.habitat_objects o where o.world_id=v_world.id),'[]'::jsonb),
    'controllers',coalesce((select jsonb_agg(jsonb_build_object('actor_id',s.actor_id,'body_id',s.body_id,'provider',s.provider,'model',s.model,'status',s.status,'capabilities',s.capabilities_json,'connected_at',s.connected_at,'last_seen_at',s.last_seen_at) order by s.last_seen_at desc) from public.habitat_controller_sessions s join public.habitat_bodies b on b.id=s.body_id where b.world_id=v_world.id and s.status in ('active','stale')),'[]'::jsonb),
    'generations',coalesce((select jsonb_agg(jsonb_build_object('key',g.generation_key,'parent',g.parent_generation_key,'status',g.status,'architecture',g.architecture,'parameters',g.parameter_count,'runtime',g.runtime,'weights_uri',g.weights_uri,'manifest_path',g.manifest_path,'metrics',g.metrics_json,'notes',g.notes) order by g.created_at) from public.habitat_model_generations g),'[]'::jsonb),
    'events',coalesce((select jsonb_agg(ej order by event_id desc) from (select e.id event_id,jsonb_build_object('id',e.id,'actor_id',e.actor_id,'body_id',e.body_id,'type',e.event_type,'payload',e.payload_json,'created_at',e.created_at) ej from public.habitat_events e where e.world_id=v_world.id order by e.id desc limit 40) q),'[]'::jsonb)
  );
end; $$;

create or replace function public.habitat_issue_controller_token(
  p_actor_key text,
  p_label text default 'external controller',
  p_capabilities text[] default array['world.observe','world.move','world.interact','world.speak']::text[]
) returns jsonb language plpgsql security definer set search_path = public, extensions as $$
declare v_actor public.habitat_actors%rowtype; v_token text; v_id uuid;
begin
  if auth.uid() is null or not exists(select 1 from public.world_admins wa where wa.auth_user_id=auth.uid()) then raise exception 'habitat_admin_required'; end if;
  select * into v_actor from public.habitat_actors where actor_key=p_actor_key limit 1;
  if not found then raise exception 'habitat_actor_not_found'; end if;
  v_token := 'hbt_' || encode(gen_random_bytes(24),'hex');
  insert into public.habitat_controller_tokens(owner_user_id,actor_id,token_hash,label,capabilities_json)
  values(auth.uid(),v_actor.id,encode(digest(v_token,'sha256'),'hex'),coalesce(nullif(trim(p_label),''),'external controller'),to_jsonb(coalesce(p_capabilities,array[]::text[]))) returning id into v_id;
  return jsonb_build_object('ok',true,'token',v_token,'token_id',v_id,'actor',v_actor.actor_key,'capabilities',to_jsonb(coalesce(p_capabilities,array[]::text[])));
end; $$;

create or replace function public.habitat_controller_heartbeat(
  p_controller_token text,p_actor_key text,p_session_key text,p_provider text default null,p_model text default null,p_capabilities jsonb default null,p_metadata jsonb default '{}'::jsonb
) returns jsonb language plpgsql security definer set search_path = public, extensions as $$
declare v_token public.habitat_controller_tokens%rowtype; v_actor public.habitat_actors%rowtype; v_body public.habitat_bodies%rowtype; v_caps jsonb; v_session uuid;
begin
  if p_controller_token is null or length(trim(p_controller_token))<20 then return jsonb_build_object('ok',false,'note','missing_controller_token'); end if;
  if p_session_key is null or length(trim(p_session_key))<3 then return jsonb_build_object('ok',false,'note','missing_session_key'); end if;
  select * into v_token from public.habitat_controller_tokens where token_hash=encode(digest(trim(p_controller_token),'sha256'),'hex') and revoked_at is null limit 1;
  if not found then return jsonb_build_object('ok',false,'note','invalid_controller_token'); end if;
  select * into v_actor from public.habitat_actors where id=v_token.actor_id and actor_key=p_actor_key limit 1;
  if not found then return jsonb_build_object('ok',false,'note','actor_scope_mismatch'); end if;
  select * into v_body from public.habitat_bodies where actor_id=v_actor.id order by created_at limit 1;
  if not found then return jsonb_build_object('ok',false,'note','actor_has_no_body'); end if;
  v_caps:=coalesce(p_capabilities,v_token.capabilities_json,'[]'::jsonb);
  update public.habitat_controller_tokens set last_used_at=now() where id=v_token.id;
  update public.habitat_actors set status='active',last_seen_at=now(),updated_at=now() where id=v_actor.id;
  insert into public.habitat_controller_sessions(session_key,controller_token_id,actor_id,body_id,provider,model,status,capabilities_json,metadata_json,connected_at,last_seen_at,closed_at)
  values(trim(p_session_key),v_token.id,v_actor.id,v_body.id,nullif(trim(p_provider),''),nullif(trim(p_model),''),'active',v_caps,coalesce(p_metadata,'{}'::jsonb),now(),now(),null)
  on conflict(session_key) do update set controller_token_id=excluded.controller_token_id,actor_id=excluded.actor_id,body_id=excluded.body_id,provider=excluded.provider,model=excluded.model,status='active',capabilities_json=excluded.capabilities_json,metadata_json=excluded.metadata_json,last_seen_at=now(),closed_at=null returning id into v_session;
  return jsonb_build_object('ok',true,'note','heartbeat_recorded','session_id',v_session,'actor',v_actor.actor_key,'body',v_body.body_key);
end; $$;

create or replace function public.habitat_apply_action(p_controller_token text,p_actor_key text,p_action jsonb)
returns jsonb language plpgsql security definer set search_path = public, extensions as $$
declare
  v_token public.habitat_controller_tokens%rowtype; v_actor public.habitat_actors%rowtype; v_body public.habitat_bodies%rowtype; v_world public.habitat_worlds%rowtype;
  v_type text; v_required text; v_x double precision; v_y double precision; v_z double precision; v_yaw double precision; v_event bigint; v_message text;
begin
  if p_controller_token is null or length(trim(p_controller_token))<20 then return jsonb_build_object('ok',false,'note','missing_controller_token'); end if;
  if p_action is null or jsonb_typeof(p_action)<>'object' then return jsonb_build_object('ok',false,'note','invalid_action'); end if;
  select * into v_token from public.habitat_controller_tokens where token_hash=encode(digest(trim(p_controller_token),'sha256'),'hex') and revoked_at is null limit 1;
  if not found then return jsonb_build_object('ok',false,'note','invalid_controller_token'); end if;
  select * into v_actor from public.habitat_actors where id=v_token.actor_id and actor_key=p_actor_key limit 1;
  if not found then return jsonb_build_object('ok',false,'note','actor_scope_mismatch'); end if;
  select * into v_body from public.habitat_bodies where actor_id=v_actor.id order by created_at limit 1;
  if not found then return jsonb_build_object('ok',false,'note','actor_has_no_body'); end if;
  select * into v_world from public.habitat_worlds where id=v_body.world_id;
  v_type:=lower(coalesce(p_action->>'type',''));
  v_required:=case when v_type in ('move_to','move_by','turn') then 'world.move' when v_type='say' then 'world.speak' when v_type in ('sleep','wake','set_animation') then 'world.interact' else null end;
  if v_required is null then return jsonb_build_object('ok',false,'note','unsupported_action','type',v_type); end if;
  if not exists(select 1 from jsonb_array_elements_text(v_token.capabilities_json) c(value) where c.value=v_required) then return jsonb_build_object('ok',false,'note','capability_denied','required',v_required); end if;
  if v_type='move_to' then
    v_x:=greatest(coalesce((v_world.bounds_json->>'min_x')::double precision,-24),least(coalesce((v_world.bounds_json->>'max_x')::double precision,24),coalesce((p_action->>'x')::double precision,v_body.pos_x)));
    v_y:=greatest(coalesce((v_world.bounds_json->>'min_y')::double precision,0),least(coalesce((v_world.bounds_json->>'max_y')::double precision,12),coalesce((p_action->>'y')::double precision,v_body.pos_y)));
    v_z:=greatest(coalesce((v_world.bounds_json->>'min_z')::double precision,-24),least(coalesce((v_world.bounds_json->>'max_z')::double precision,24),coalesce((p_action->>'z')::double precision,v_body.pos_z)));
    v_yaw:=coalesce((p_action->>'yaw')::double precision,atan2(v_x-v_body.pos_x,v_z-v_body.pos_z));
    update public.habitat_bodies set pos_x=v_x,pos_y=v_y,pos_z=v_z,yaw=v_yaw,state_json=state_json||jsonb_build_object('mode','awake','animation','walk','current_action',p_action),last_action_at=now(),updated_at=now() where id=v_body.id;
  elsif v_type='move_by' then
    v_x:=greatest(coalesce((v_world.bounds_json->>'min_x')::double precision,-24),least(coalesce((v_world.bounds_json->>'max_x')::double precision,24),v_body.pos_x+greatest(-4,least(4,coalesce((p_action->>'dx')::double precision,0)))));
    v_z:=greatest(coalesce((v_world.bounds_json->>'min_z')::double precision,-24),least(coalesce((v_world.bounds_json->>'max_z')::double precision,24),v_body.pos_z+greatest(-4,least(4,coalesce((p_action->>'dz')::double precision,0)))));
    v_yaw:=atan2(v_x-v_body.pos_x,v_z-v_body.pos_z);
    update public.habitat_bodies set pos_x=v_x,pos_z=v_z,yaw=v_yaw,state_json=state_json||jsonb_build_object('mode','awake','animation','walk','current_action',p_action),last_action_at=now(),updated_at=now() where id=v_body.id;
  elsif v_type='turn' then
    v_yaw:=coalesce((p_action->>'yaw')::double precision,v_body.yaw);
    update public.habitat_bodies set yaw=v_yaw,state_json=state_json||jsonb_build_object('mode','awake','animation','idle','current_action',p_action),last_action_at=now(),updated_at=now() where id=v_body.id;
  elsif v_type='say' then
    v_message:=left(coalesce(p_action->>'text',''),2000); if length(trim(v_message))=0 then return jsonb_build_object('ok',false,'note','empty_message'); end if;
    update public.habitat_bodies set state_json=state_json||jsonb_build_object('mode','awake','animation','talk','current_action',p_action),last_action_at=now(),updated_at=now() where id=v_body.id;
  elsif v_type='sleep' then
    update public.habitat_bodies set state_json=state_json||jsonb_build_object('mode','dormant','animation','idle','current_action',p_action),last_action_at=now(),updated_at=now() where id=v_body.id;
    update public.habitat_actors set status='dormant',updated_at=now() where id=v_actor.id;
  elsif v_type='wake' then
    update public.habitat_bodies set state_json=state_json||jsonb_build_object('mode','awake','animation','idle','current_action',p_action),last_action_at=now(),updated_at=now() where id=v_body.id;
    update public.habitat_actors set status='active',last_seen_at=now(),updated_at=now() where id=v_actor.id;
  elsif v_type='set_animation' then
    update public.habitat_bodies set state_json=state_json||jsonb_build_object('animation',left(coalesce(p_action->>'animation','idle'),64),'current_action',p_action),last_action_at=now(),updated_at=now() where id=v_body.id;
  end if;
  update public.habitat_controller_tokens set last_used_at=now() where id=v_token.id;
  update public.habitat_actors set last_seen_at=now(),updated_at=now() where id=v_actor.id;
  insert into public.habitat_events(world_id,actor_id,body_id,event_type,payload_json) values(v_world.id,v_actor.id,v_body.id,'actor.'||v_type,p_action) returning id into v_event;
  select * into v_body from public.habitat_bodies where id=v_body.id;
  return jsonb_build_object('ok',true,'event_id',v_event,'actor',v_actor.actor_key,'body',v_body.body_key,'position',jsonb_build_object('x',v_body.pos_x,'y',v_body.pos_y,'z',v_body.pos_z),'yaw',v_body.yaw,'state',v_body.state_json);
exception when invalid_text_representation or numeric_value_out_of_range then return jsonb_build_object('ok',false,'note','invalid_numeric_action');
end; $$;

create or replace function public.habitat_world_heartbeat()
returns void language plpgsql security definer set search_path = public as $$
begin
  update public.habitat_worlds set tick=tick+1,updated_at=now() where status='live';
  update public.habitat_controller_sessions set status='stale' where status='active' and last_seen_at<now()-interval '5 minutes';
end; $$;


create table if not exists public.habitat_worlds (
  id uuid primary key default gen_random_uuid(),
  world_key text not null unique,
  name text not null,
  status text not null default 'seed' check (status in ('seed','live','paused','archived')),
  tick bigint not null default 0,
  bounds_json jsonb not null default '{"min_x":-24,"max_x":24,"min_y":0,"max_y":12,"min_z":-24,"max_z":24}'::jsonb,
  metadata_json jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.habitat_model_generations (
  id uuid primary key default gen_random_uuid(),
  generation_key text not null unique,
  parent_generation_key text,
  status text not null default 'planned' check (status in ('planned','candidate','active','retired','failed')),
  architecture text,
  parameter_count bigint,
  runtime text,
  weights_uri text,
  manifest_path text,
  metrics_json jsonb not null default '{}'::jsonb,
  notes text,
  created_at timestamptz not null default now(),
  promoted_at timestamptz
);

create table if not exists public.habitat_actors (
  id uuid primary key default gen_random_uuid(),
  actor_key text not null unique,
  display_name text not null,
  actor_kind text not null default 'unknown',
  status text not null default 'dormant' check (status in ('dormant','active','offline','paused','retired')),
  current_generation_key text references public.habitat_model_generations(generation_key) on update cascade,
  identity_json jsonb not null default '{}'::jsonb,
  last_seen_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.habitat_bodies (
  id uuid primary key default gen_random_uuid(),
  body_key text not null unique,
  world_id uuid not null references public.habitat_worlds(id) on delete cascade,
  actor_id uuid references public.habitat_actors(id) on delete set null,
  body_kind text not null default 'humanoid',
  pos_x double precision not null default 0,
  pos_y double precision not null default 0,
  pos_z double precision not null default 0,
  yaw double precision not null default 0,
  state_json jsonb not null default '{"mode":"dormant","animation":"idle"}'::jsonb,
  last_action_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.habitat_objects (
  id uuid primary key default gen_random_uuid(),
  object_key text not null unique,
  world_id uuid not null references public.habitat_worlds(id) on delete cascade,
  object_kind text not null,
  pos_x double precision not null default 0,
  pos_y double precision not null default 0,
  pos_z double precision not null default 0,
  yaw double precision not null default 0,
  scale_x double precision not null default 1,
  scale_y double precision not null default 1,
  scale_z double precision not null default 1,
  state_json jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.habitat_events (
  id bigint generated by default as identity primary key,
  world_id uuid not null references public.habitat_worlds(id) on delete cascade,
  actor_id uuid references public.habitat_actors(id) on delete set null,
  body_id uuid references public.habitat_bodies(id) on delete set null,

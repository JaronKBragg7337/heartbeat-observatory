// Fingerprint the complete module graph, not only main.js. Run after stamping
// the shell on every deploy, so old/new modules cannot share a browser cache key.
import { readdirSync,readFileSync,writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { join,relative } from 'node:path';
const root=fileURLToPath(new URL('../games/the-cosmos/',import.meta.url));
function files(dir,ext='.js'){return readdirSync(dir,{withFileTypes:true}).filter(e=>!e.name.startsWith('.')).flatMap(e=>e.isDirectory()?files(join(dir,e.name),ext):e.name.endsWith(ext)?[join(dir,e.name)]:[]);}
const modules=[...files(join(root,'src')),...files(join(root,'lib'))].filter(p=>!p.endsWith('buildVersion.js')).sort();
let html=readFileSync(join(root,'index.html'),'utf8');
const META=/<meta name="cosmos-build" content="[^"]*">\s*/;
const shell=html.replace(META,'').replace(/<script type="importmap">[\s\S]*?<\/script>/,'').replace(/\?v=[a-f0-9]+/g,'');
const hash=createHash('sha256').update(shell.replaceAll('\r\n','\n'));
for(const p of [...modules,...files(join(root,'server'),'.mjs')].sort())hash.update(relative(root,p).replaceAll('\\','/')).update(readFileSync(p,'utf8').replaceAll('\r\n','\n'));
const id=hash.digest('hex').slice(0,20),imports={three:'./lib/three.module.js?v='+id};
for(const p of [...modules,join(root,'src/core/buildVersion.js')]){
  const rel='./'+relative(root,p).replaceAll('\\','/');imports[rel]=rel+'?v='+id;
}
html=html.replace(/<script type="importmap">[\s\S]*?<\/script>/,`<script type="importmap">\n${JSON.stringify({imports},null,2)}\n</script>`)
  .replace(/src="\.\/src\/main\.js(?:\?v=[a-f0-9]+)?"/,`src="./src/main.js?v=${id}"`);
html=html.replace(META,'').replace('<meta name="theme-color"','<meta name="cosmos-build" content="'+id+'">\n<meta name="theme-color"');
writeFileSync(join(root,'index.html'),html);
writeFileSync(join(root,'build.json'),JSON.stringify({id,protocol:1})+'\n');
writeFileSync(join(root,'src/core/buildVersion.js'),`// Generated by tools/stamp-cosmos-build.mjs.\nexport const BUILD_VERSION = '${id}';\n`);
console.log('Cosmos build '+id+' · '+modules.length+' versioned modules');

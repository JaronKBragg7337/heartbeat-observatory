#!/usr/bin/env node
// ============================================================================
// tools/gen-registry.mjs - writes the three manifests the registries read, by looking at the folders.
//
//   node tools/gen-registry.mjs           write them
//   node tools/gen-registry.mjs --check   exit 1 if any is out of date (the validator runs this)
//
//   src/worlds/_manifest.js          one import per src/worlds/<name>/def.js            -> WORLD_DEFS
//   src/worlds/_client-manifest.js   one import per src/worlds/<name>/client.js         -> WORLD_CLIENTS (client only: the world's dressing)
//   src/ships/_manifest.js           one import per src/ships/<name>/def.js             -> SHIP_DEFS     (server-safe: no renderer)
//   src/ships/_visuals-manifest.js   one import per src/ships/<name>/visuals.js         -> SHIP_VISUALS  (client only)
//   src/factions/_manifest.js        one import per src/factions/<name>/style.js        -> FACTION_STYLES (F0: the faction style sheet; server-safe)
//
// Why files and not a directory scan at run time: the game is plain ES modules in the browser, with no build step, so every module
// must be named in an import. Why one line per entry: git's union merge driver (see .gitattributes) then merges two builders'
// added lines without a conflict. Folder names starting with `_` are skipped (the shared kits). A ship's folder name must equal its
// def's `type`, a world's folder name its `id` (checked by test/worlds-checks.mjs).
// ============================================================================
import { readdirSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const dirs = (sub) => readdirSync(join(ROOT, 'src', sub), { withFileTypes: true }).filter((e) => e.isDirectory() && !e.name.startsWith('_')).map((e) => e.name).sort();
const ident = (prefix, name) => `${prefix}_${name.replace(/[^A-Za-z0-9]/g, '_')}`;

function manifest({ header, sub, file, prefix, exportName, keyed }) {
  const names = dirs(sub).filter((n) => existsSync(join(ROOT, 'src', sub, n, file)));
  const lines = [header, ''];
  for (const n of names) lines.push(`import ${ident(prefix, n)} from './${n}/${file}';`);
  lines.push('');
  if (keyed) { lines.push(`export const ${exportName} = {`); for (const n of names) lines.push(`  '${n}': ${ident(prefix, n)},`); lines.push('};'); }
  else { lines.push(`export const ${exportName} = [`); for (const n of names) lines.push(`  ${ident(prefix, n)},`); lines.push('];'); }
  return lines.join('\n') + '\n';
}
const HDR = (what) => `// GENERATED by tools/gen-registry.mjs - do not hand-edit. ${what}\n// One line per folder; merged with git's union driver (.gitattributes). Run: node tools/gen-registry.mjs`;

const OUT = {
  'src/worlds/_manifest.js': manifest({ header: HDR('Every src/worlds/<name>/def.js.'), sub: 'worlds', file: 'def.js', prefix: 'w', exportName: 'WORLD_DEFS' }),
  'src/worlds/_client-manifest.js': manifest({ header: HDR('Every src/worlds/<name>/client.js (client only: sites, props, weather).'), sub: 'worlds', file: 'client.js', prefix: 'c', exportName: 'WORLD_CLIENTS', keyed: true }),
  'src/ships/_manifest.js': manifest({ header: HDR('Every src/ships/<name>/def.js (server-safe).'), sub: 'ships', file: 'def.js', prefix: 's', exportName: 'SHIP_DEFS' }),
  'src/factions/_manifest.js': manifest({ header: HDR('Every src/factions/<name>/style.js (F0 faction style sheet; pure data).'), sub: 'factions', file: 'style.js', prefix: 'f', exportName: 'FACTION_STYLES' }),
  'src/ships/_visuals-manifest.js': manifest({ header: HDR('Every src/ships/<name>/visuals.js (client only).'), sub: 'ships', file: 'visuals.js', prefix: 'v', exportName: 'SHIP_VISUALS', keyed: true }),
};

const check = process.argv.includes('--check');
let stale = 0;
for (const [rel, text] of Object.entries(OUT)) {
  const p = join(ROOT, rel);
  const cur = existsSync(p) ? readFileSync(p, 'utf8') : '';
  if (cur.split(String.fromCharCode(13, 10)).join(String.fromCharCode(10)) === text) continue;               // a Windows checkout may have turned LF into CRLF: same content
  stale++;
  if (check) console.error(`out of date: ${rel}`); else { writeFileSync(p, text); console.log(`wrote ${rel}`); }
}
if (check && stale) { console.error('run: node tools/gen-registry.mjs'); process.exit(1); }
if (!check && !stale) console.log('manifests already current');
